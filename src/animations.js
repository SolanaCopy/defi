// Shared framer-motion variants. Kept in their own module so extracted
// sections (LandingSections.jsx) and App.jsx use the exact same object
// identities — passing a fresh variants object on every render would defeat
// the memoisation those sections rely on.

export const fadeUp = {
  hidden: { opacity: 0, y: 40 },
  visible: (i = 0) => ({
    opacity: 1, y: 0,
    transition: { duration: 0.7, delay: i * 0.12, ease: [0.25, 0.46, 0.45, 0.94] }
  })
};

